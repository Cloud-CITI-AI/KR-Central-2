/**
 * Generates src/gen/routes-table.ts (the schema-free route table of the browser client) from the route registry.
 *   pnpm --filter @kr/contracts openapi:generate   → writes it next to openapi.yaml
 *   pnpm --filter @kr/contracts openapi:check      → fails if it is out of date (CI, build)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { deriveRouteTable } from "../src/route-table-derive.ts";
import { ROUTES } from "../src/routes.ts";

const target = fileURLToPath(new URL("../src/gen/routes-table.ts", import.meta.url));

function build(): string {
  const table = deriveRouteTable(ROUTES);
  const entries = Object.entries(table).map(
    ([operationId, e]) =>
      `  ${operationId}: {\n` +
      `    method: ${JSON.stringify(e.method)},\n` +
      `    path: ${JSON.stringify(e.path)},\n` +
      `    csrf: ${String(e.csrf)},\n` +
      `    ifMatch: ${JSON.stringify(e.ifMatch)},\n` +
      `    idempotencyKey: ${JSON.stringify(e.idempotencyKey)},\n` +
      `    multipart: ${String(e.multipart)},\n` +
      `  },\n`,
  );
  return (
    "// GENERATED by packages/contracts/scripts/generate-routes-table.ts from src/routes.ts: do not edit (X10).\n" +
    "// Regenerate with `pnpm openapi:generate`.\n" +
    'import type { RouteTableEntry } from "../route-table-derive.js";\n\n' +
    `export const ROUTE_TABLE = {\n${entries.join("")}} as const satisfies Record<string, RouteTableEntry>;\n`
  );
}

const out = build();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = readFileSync(target, "utf8");
  } catch {
    // Missing: reported as out of date below.
  }
  if (current !== out) {
    console.error("src/gen/routes-table.ts is out of date. Run: pnpm --filter @kr/contracts openapi:generate");
    process.exit(1);
  }
  console.log("src/gen/routes-table.ts is up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
