/**
 * Generates openapi.yaml (OpenAPI 3.1) from the route registry and zod schemas.
 *   pnpm --filter @kr/contracts openapi:generate   → writes openapi.yaml
 *   pnpm --filter @kr/contracts openapi:check      → fails if openapi.yaml is out of date (CI)
 */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createDocument, type ZodOpenApiOperationObject, type ZodOpenApiPathsObject } from "zod-openapi";
import { stringify } from "yaml";
import { z } from "zod";
import { ROUTES, type RouteDef } from "../src/routes.ts";

const target = fileURLToPath(new URL("../openapi.yaml", import.meta.url));

function responsesOf(r: RouteDef): ZodOpenApiOperationObject["responses"] {
  const out: Record<string, unknown> = {};
  for (const [status, res] of Object.entries(r.responses)) {
    const contentType = res.contentType ?? "application/json";
    out[status] = {
      description: res.description,
      ...(res.schema
        ? { content: { [contentType]: { schema: res.schema } } }
        : res.contentType
          ? { content: { [res.contentType]: { schema: { type: "string", format: "binary" } } } }
          : {}),
      ...(res.headers
        ? {
            headers: z.object(
              Object.fromEntries(Object.entries(res.headers).map(([h, d]) => [h, z.string().meta({ description: d })])),
            ),
          }
        : {}),
    };
  }
  return out as ZodOpenApiOperationObject["responses"];
}

function build(): string {
  const paths: ZodOpenApiPathsObject = {};
  for (const r of ROUTES as readonly RouteDef[]) {
    const req = r.request;
    const op: ZodOpenApiOperationObject = {
      operationId: r.operationId,
      summary: r.summary,
      tags: [r.tag],
      description: `Authorisation: ${r.authz}`,
      ...(r.auth === "public" ? { security: [] } : {}),
      responses: responsesOf(r),
    };
    if (req) {
      const requestParams: NonNullable<ZodOpenApiOperationObject["requestParams"]> = {};
      if (req.params) requestParams.path = req.params as never;
      if (req.query) requestParams.query = req.query as never;
      if (req.headers) requestParams.header = req.headers as never;
      if (Object.keys(requestParams).length) op.requestParams = requestParams;
      if (req.body) {
        op.requestBody = req.multipart
          ? {
              required: true,
              content: {
                "multipart/form-data": {
                  schema: {
                    type: "object",
                    description: "Text fields (see UploadFields) followed by exactly one `file` part",
                    properties: {
                      checkpointKey: { type: "string" },
                      slot: { type: "string" },
                      conditionId: { type: "string", format: "uuid" },
                      file: { type: "string", format: "binary" },
                    },
                    required: ["file"],
                  },
                },
              },
            }
          : { required: true, content: { "application/json": { schema: req.body } } };
      }
    }
    const p = (paths[r.path] ??= {}) as Record<string, ZodOpenApiOperationObject>;
    p[r.method.toLowerCase()] = op;
  }
  const doc = createDocument({
    openapi: "3.1.0",
    info: {
      title: "KR Subdivision Tracker API",
      version: "1.0.0",
      description:
        "Internal API behind the web app's same-origin proxy (/api/v1/* → /v1/*). Session cookie auth (Entra ID OIDC); CSRF header on writes; RFC 9457 errors.",
    },
    servers: [{ url: "/api", description: "Through the web app proxy" }],
    components: {
      securitySchemes: { session: { type: "apiKey", in: "cookie", name: "__Host-kr_session" } },
    },
    security: [{ session: [] }],
    paths,
  });
  return `# GENERATED by packages/contracts/scripts/generate-openapi.ts — do not edit (X10).\n${stringify(doc, { aliasDuplicateObjects: false })}`;
}

const out = build();
if (process.argv.includes("--check")) {
  const current = readFileSync(target, "utf8");
  if (current !== out) {
    console.error("openapi.yaml is out of date. Run: pnpm --filter @kr/contracts openapi:generate");
    process.exit(1);
  }
  console.log("openapi.yaml is up to date");
} else {
  writeFileSync(target, out);
  console.log(`wrote ${target}`);
}
