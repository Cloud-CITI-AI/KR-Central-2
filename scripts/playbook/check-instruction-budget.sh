#!/usr/bin/env bash
# Enforces instruction-file size budgets (docs/03 §3.4). Usage: check-instruction-budget.sh [repo-root]
# Budgets (non-blank lines, excluding HTML comments):
#   root AGENTS.md <= 150 · package AGENTS.md <= 80 · CLAUDE.md <= 40 (excluding the @AGENTS.md import)
#   .github/copilot-instructions.md <= 40 · each .github/instructions/*.instructions.md <= 40
#   any loaded chain (AGENTS.md + all ancestor AGENTS.md) <= 250
set -euo pipefail
root="$(cd "${1:-.}" && pwd)"
fail=0

count() { # non-blank, non-comment lines
  python3 - "$1" <<'PY'
import re,sys
t=open(sys.argv[1]).read()
t=re.sub(r"<!--.*?-->","",t,flags=re.S)
print(sum(1 for l in t.splitlines() if l.strip()))
PY
}
check() { # file limit label
  local n; n=$(count "$1")
  if (( n > $2 )); then echo "::error file=${1#$root/}::$3 has $n lines (budget $2)"; fail=1; else echo "ok  ${1#$root/}: $n/$2"; fi
}

while IFS= read -r f; do
  if [[ "$f" == "$root/AGENTS.md" ]]; then check "$f" 150 "root AGENTS.md"; else check "$f" 80 "package AGENTS.md"; fi
  # chain
  total=0; d="$(dirname "$f")"
  while :; do
    [[ -f "$d/AGENTS.md" ]] && total=$(( total + $(count "$d/AGENTS.md") ))
    [[ "$d" == "$root" ]] && break
    d="$(dirname "$d")"
  done
  if (( total > 250 )); then echo "::error file=${f#$root/}::instruction chain for ${f#$root/} is $total lines (budget 250)"; fail=1; fi
done < <(find "$root" -name AGENTS.md -not -path '*/node_modules/*' -not -path '*/.git/*' -not -path '*/.playbook/*')

while IFS= read -r f; do
  n=$(grep -v '^@AGENTS.md' "$f" | python3 -c 'import re,sys;t=re.sub(r"<!--.*?-->","",sys.stdin.read(),flags=re.S);print(sum(1 for l in t.splitlines() if l.strip()))')
  if (( n > 40 )); then echo "::error file=${f#$root/}::CLAUDE.md has $n lines beyond the import (budget 40)"; fail=1; else echo "ok  ${f#$root/}: $n/40"; fi
  head -n 3 "$f" | grep -q '^@AGENTS.md' || { echo "::error file=${f#$root/}::CLAUDE.md must import @AGENTS.md in its first lines (ADR-0001)"; fail=1; }
done < <(find "$root" -name CLAUDE.md -not -path '*/node_modules/*' -not -path '*/.git/*' -not -path '*/.playbook/*')

for f in "$root/.github/copilot-instructions.md" "$root"/.github/instructions/*.instructions.md; do
  [[ -f "$f" ]] && check "$f" 40 "${f#$root/}"
done

# Anti-patterns: generated context files and directory dumps
if grep -RIlE --include=AGENTS.md '(Generated by|auto-generated|├──|└──)' "$root" --exclude-dir=node_modules --exclude-dir=.git --exclude-dir=.playbook 2>/dev/null; then
  echo "::error::AGENTS.md appears generated or contains a directory tree (anti-pattern, docs/03 §3.5)"; fail=1
fi
exit $fail
