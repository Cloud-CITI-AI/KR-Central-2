export interface ParityResult {
  readonly file: string;
  readonly title: string;
  readonly theme: "light" | "dark";
  readonly device: "desktop" | "mobile";
  readonly expected: string;
  readonly status: "compared" | "absent";
  readonly ratio?: number;
  readonly reference?: { readonly width: number; readonly height: number };
  readonly actual?: { readonly width: number; readonly height: number };
}

const size = (s: { width: number; height: number } | undefined): string =>
  s ? `${s.width.toString()}×${s.height.toString()}` : "–";

/** A Markdown table with padded columns, the way Prettier writes one (so the committed checklist passes `format:check`). */
function table(header: readonly string[], rows: readonly (readonly string[])[]): string[] {
  const widths = header.map((cell, column) =>
    Math.max(cell.length, 3, ...rows.map((row) => (row[column] ?? "").length)),
  );
  const line = (cells: readonly string[]): string =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] ?? 0)).join(" | ")} |`;
  return [line(header), `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`, ...rows.map(line)];
}

/** The sign-off checklist (Markdown) for a parity run: one row per prototype view, in the prototype's file order. */
export function renderChecklist(results: readonly ParityResult[]): string {
  const rows = [...results]
    .sort((a, b) => a.file.localeCompare(b.file))
    .map((result) => {
      const ratio = result.ratio === undefined ? "n/a (not in the app)" : `${(result.ratio * 100).toFixed(1)} %`;
      const sizes = result.status === "compared" ? `${size(result.reference)} → ${size(result.actual)}` : "–";
      return [
        "[ ]",
        `\`${result.file}\``,
        `${result.title} (${result.theme}, ${result.device})`,
        sizes,
        ratio,
        result.expected,
      ];
    });
  return [
    "# Prototype parity checklist (WP-19)",
    "",
    "Generated by `pnpm --filter @kr/web test:e2e` (`e2e/parity/parity.spec.ts`; `PARITY_UPDATE_CHECKLIST=1` rewrites this file). Each row compares a",
    "screenshot of the prototype's blank demo job (`docs/reference/prototype/screenshots/blank-*.png`) with the same view of the app, seeded with the",
    'same synthetic blank job (DEMO-000 "Blank demo job", Survey-Strata, nothing set). The diff ratio is the share of pixels that differ by more than',
    "24/255 in a channel, over the larger of the two images, top left aligned: a taller or shorter page therefore counts as different below the",
    "shorter edge. It is report-only. The side-by-side images (prototype | app | difference in red) are attached to the Playwright report and",
    "written to `apps/web/test-results/parity/`.",
    "",
    "A human ticks a row once its differences are the expected ones (or turns an unexpected one into an issue).",
    "",
    ...table(["Signed off", "View", "What", "Size (prototype → app)", "Diff ratio", "Expected differences"], rows),
    "",
  ].join("\n");
}
